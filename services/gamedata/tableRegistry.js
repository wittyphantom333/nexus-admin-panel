const _byKey = new Map(ENTRIES.map(e => [e.key, e]));
const _byDb = { auth: [], world: [], character: [] };
for (const e of ENTRIES) _byDb[e.db].push(e.key);

function get(key) {
  const e = _byKey.get(key);
  if (!e) {
    const err = new Error(`Unknown gamedata resource: ${key}`);
    err.status = 404;
    throw err;
  }
  // Sanity: all identifiers must match the allow-list.
  for (const arr of [e.listColumns, e.searchColumns, e.sortable, e.updatable, [e.table, e.primaryKey]]) {
    for (const c of arr) {
      if (c && !IDENT.test(c)) {
        throw new Error(`Invalid identifier in registry entry ${e.key}: ${c}`);
      }
    }
  }
  return e;
}

function listKeys() {
  return ENTRIES.map(e => ({
    key: e.key, label: e.label, icon: e.icon,
    db: e.db, table: e.table, editable: e.editable,
    primaryKey: e.primaryKey,
    listColumns: e.listColumns,
    searchable: e.searchable,
    sortable: e.sortable,
    updatable: e.updatable,
  }));
}

function pool(entry) {
  if (entry.db === 'auth') return require('../../db').auth();
  if (entry.db === 'world') return require('../../db').world();
  if (entry.db === 'character') return require('../../db').character();
  const err = new Error(`Unknown db: ${entry.db}`);
  err.status = 500;
  throw err;
}

module.exports = { get, listKeys, pool, ENTRIES, IDENT };
